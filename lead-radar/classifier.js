// AI-классификатор находок.
//
// Словари отвечают на вопрос «есть ли в тексте нужные слова». Этого мало:
// «ищу квартиру снять на месяц» и «ищу квартиру купить, бюджет 300к» состоят
// из одних и тех же слов, а клиент — только второй. То же и во второй теме:
// «ищу разработчика» и «ищу работу разработчиком» словарь различает с трудом,
// а модель — легко. Заодно она вытаскивает бюджет, сроки и требования, чтобы
// менеджер сразу видел, с чем идти к человеку.
//
// Словари при этом остаются: они работают предфильтром и отсекают ~95%
// сообщений до вызова модели. Без них классификатор разбирал бы каждое
// «всем привет» — дорого и бессмысленно.
//
// У каждого профиля свой промпт и своя схема ответа: у покупателя квартиры и
// у заказчика приложения общего мало, и общая схема заставляла бы модель
// придумывать поля, которых в сообщении нет.

import Anthropic from "@anthropic-ai/sdk";
import { z } from "zod";
import { zodOutputFormat } from "@anthropic-ai/sdk/helpers/zod";

export const AI_ENABLED = Boolean(process.env.ANTHROPIC_API_KEY);

/** Ниже этого балла модели находка не показывается. */
