// AI-классификатор находок.
//
// Словари отвечают на вопрос «есть ли в тексте нужные слова». Этого мало:
// «ищу квартиру снять на месяц» и «ищу квартиру купить, бюджет 300к» состоят
// из одних и тех же слов, а клиент — только второй. То же и во второй теме:
// «ищу разработчика» и «ищу работу разработчиком» словарь различает с трудом,
// а модель — легко. Заодно она вытаскивает бюджет, сроки и требования, чтобы
// менеджер сразу видел, с чем идти к человеку.
//
// Словари при этом остаются: они работают предфильтром и отсекают ~95%
// сообщений до вызова модели. Без них классификатор разбирал бы каждое
// «всем привет» — дорого и бессмысленно.
//
// У каждого профиля свой промпт и своя схема ответа: у покупателя квартиры и
// у заказчика приложения общего мало, и общая схема заставляла бы модель
// придумывать поля, которых в сообщении нет.

import Anthropic from "@anthropic-ai/sdk";
import { z } from "zod";
import { zodOutputFormat } from "@anthropic-ai/sdk/helpers/zod";

export const AI_ENABLED = Boolean(process.env.ANTHROPIC_API_KEY);

/** Ниже этого балла модели находка не показывается. */
export const AI_MIN_SCORE = Number(process.env.AI_MIN_SCORE ?? 55);

const MODEL = process.env.AI_MODEL ?? "claude-opus-5";

const client = AI_ENABLED ? new Anthropic() : null;

// Общая часть схемы: по ней движок решает, показывать находку или нет,
// и она одинакова для всех тем.
const common = {
  is_lead: z.boolean(),
  lead_score: z.number(),
  temperature: z.enum(["HOT", "WARM", "LOW", "NOISE"]),
  budget: z.string(),
  currency: z.string(),
  timeframe: z.string(),
  requirements: z.array(z.string()),
  language: z.string(),
  reason: z.string(),
  sales_angle: z.string(),
  confidence: z.number(),
};

const EstateSchema = z.object({
  ...common,
  intent: z.enum([
    "BUY",
    "SELL",
    "RENT",
    "HIRE",
    "LOOKING_FOR",
    "QUESTION",
    "RESEARCH",
    "ADVERTISEMENT",
    "OTHER",
  ]),
  category: z.string(),
  location: z.string(),
});

const WarmSchema = z.object({
  ...common,
  intent: z.enum([
    "RELOCATING",
    "ALREADY_MOVED",
    "RESIDENCY",
    "BUSINESS_SETUP",
    "JUST_ASKING",
    "ADVERTISEMENT",
    "OTHER",
  ]),
  /** Страна, куда человек перебирается. */
  country: z.string(),
  /** На каком он этапе: планирует, оформляет, уже переехал. */
  stage: z.string(),
  /** Через сколько ему понадобится жильё, по твоей оценке. */
  horizon: z.string(),
});

