/** Минимальная длина сообщения. Короткие реплики чаще мусор, но не всегда. */
export const MIN_LENGTH = 15;

/**
 * Упоминание денег — сильный сигнал намерения даже без слов «ищу» и «куплю».
 * «Есть что-то в районе 90к?» или «до 250 000$» — это разговор о покупке.
 */
// Граница слова \b в JavaScript считает «словом» только латиницу и цифры,
// поэтому после кириллической «к» она не срабатывает и «60к» не находилось.
// Вместо \b — явная проверка, что дальше не идёт буква.
const MONEY_RE =
  /\d[\d\s.,]*\s*(к(?![а-яё])|k(?![a-z])|тыс|млн|000|\$|€|₽|долл|евро|руб|драм|лари|дирх)/i;

/** ё → е, всё в нижний регистр: иначе «жильё» и «жилье» — разные слова. */
export function normalize(text) {
  return text.toLowerCase().replace(/ё/g, "е");
}

function findMatches(haystack, list) {
  return list.filter((word) => haystack.includes(word));
}

/**
 * Разбирает сообщение. Возвращает null, если это не лид, иначе —
 * какие именно слова сработали (их полезно видеть в уведомлении,
 * чтобы на ходу подкручивать словари).
 *
 * chatTitle нужен вот зачем: в чате «Русские в Дубае» страну вслух не называют,
 * она очевидна из контекста. Там пишут просто «думаю купить студию, что
 * посоветуете». Если требовать гео только в тексте, такие сообщения — а это
 * лучшие лиды — теряются полностью. Поэтому название чата тоже считается за гео.
 */
export function matchLead(text, chatTitle = "") {
  if (!text || text.length < MIN_LENGTH) return null;

  const haystack = normalize(text);

  const stop = findMatches(haystack, STOP);
  if (stop.length) return null;

  // Аренда без признаков покупки — не наш клиент. Это отсеивает и объявления
  // «сдам 2-комн», и тех, кто ищет жильё на два месяца.
  const buySignals = findMatches(haystack, BUY_SIGNAL);
  const rentalChat = findMatches(normalize(chatTitle), RENTAL_CHAT).length > 0;
  if ((findMatches(haystack, RENTAL).length || rentalChat) && !buySignals.length) {
    return null;
  }

  const geo = findMatches(haystack, GEO);
  const geoFromChat = findMatches(normalize(chatTitle), GEO);
  if (!geo.length && !geoFromChat.length) return null;

  const money = MONEY_RE.test(haystack);
  const topic = findMatches(haystack, TOPIC);

  // «В Батуми есть что-то в районе 60к?» — слова «квартира» нет, но город
  // назван прямо и озвучен бюджет. В чатах так спрашивают постоянно, поэтому
  // сумма заменяет тему. Условий три, и все нужны: город в самом тексте
  // (названия чата мало), знак вопроса и короткое сообщение — иначе под
  // правило подпадает любое объявление с городом и ценником.
  const moneyInsteadOfTopic =
    money && geo.length && haystack.includes("?") && text.length < 200;
  if (!topic.length && !moneyInsteadOfTopic) return null;
  if (!topic.length) topic.push("названа сумма вместо предмета");

  // Слабая тема идёт в отчёт только как дополнение — сама по себе она сюда
  // уже не приводит, поскольку без настоящей темы мы вышли строкой выше.
  topic.push(...findMatches(haystack, WEAK_TOPIC));

  // Вопрос без слов-намерений тоже считается: «кто покупал квартиру в Батуми?»
  const intent = findMatches(haystack, INTENT);
  // Намерение засчитывается тремя путями: слово из списка, вопрос
  // или упоминание суммы. Раньше было только первые два — из-за этого
  // терялись реплики вроде «в Батуми есть что-то в районе 60к».
  if (!intent.length && !haystack.includes("?") && !money) return null;

  if (money && !intent.length) intent.push("упомянута сумма");

  // Оценка «горячести». Нужна, чтобы в потоке было видно, кому отвечать
  // первым, и чтобы разбор истории присылал только лучшее, а не всё подряд.
  let score = 0;
  if (buySignals.length) score += 3;
  if (money) score += 2;
  if (findMatches(haystack, STRONG_INTENT).length) score += 2;
  if (geo.length) score += 1; // город назван прямо, а не взят из чата
  score += Math.min(topic.length, 2);
  if (findMatches(haystack, URGENCY).length) score += 1;

  const level = score >= 6 ? "hot" : score >= 4 ? "warm" : "cold";

  return {
    geo: geo.length ? geo : geoFromChat.map((g) => `${g} (из названия чата)`),
    topic,
    intent,
    buySignals,
    score,
    level,
    /** Значок для уведомления — видно с первого взгляда. */
    badge: level === "hot" ? "🔥" : level === "warm" ? "🟡" : "⚪️",
  };
}
