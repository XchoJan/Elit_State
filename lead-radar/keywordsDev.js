/**
 * Минимальная длина. Выше, чем в недвижимости: «нужен сайт» без единой
 * подробности — это не заказ, а начало разговора ни о чём, и таких реплик
 * в чатах разработчиков очень много.
 */
export const MIN_LENGTH = 25;

/** Деньги в тексте — тот же признак, что и в недвижимости. */
const MONEY_RE =
  /\d[\d\s.,]*\s*(к(?![а-яё])|k(?![a-z])|тыс|млн|000|\$|€|₽|долл|евро|руб|драм|лари)/i;

function findMatches(haystack, list) {
  return list
    .filter((item) => (item.re ? item.re.test(haystack) : haystack.includes(item)))
    .map((item) => item.label ?? item);
}

/**
 * Разбирает сообщение как возможный заказ на разработку.
 *
 * chatTitle здесь не даёт гео, как в недвижимости, но подсказывает тему:
 * в чате «Заказы на разработку» слово «сайт» весит больше, чем в чате
 * релокантов. Пока используем его только для отчёта.
 */
export function matchDevLead(text, chatTitle = "") {
  if (!text || text.length < MIN_LENGTH) return null;

  const haystack = normalize(text);

  if (findMatches(haystack, STOP).length) return null;

  // Исполнитель, предлагающий себя, — не клиент. Пропускаем только если он
  // при этом сам ищет подрядчика: «делаю сайты, нужен бэкендер на проект».
  const client = findMatches(haystack, CLIENT_SIGNAL);
  if (findMatches(haystack, SUPPLIER).length && !client.length) return null;

  const role = findMatches(haystack, ROLE);
  const task = findMatches(haystack, TASK);
  if (!role.length && !task.length) return null;

  const money = MONEY_RE.test(haystack);

  // Предмет назван — но нужен ещё признак заказчика: прямая формулировка
  // из CLIENT_SIGNAL или названная сумма.
  //
  // В недвижимости знак вопроса засчитывается за намерение, и это работает:
  // «кто покупал квартиру в Батуми?» — почти всегда клиент. Здесь так нельзя.
  // Чаты разработчиков состоят из вопросов про код («как лучше сделать
  // авторизацию через API в Next.js?»), и вопрос как признак намерения
  // превратил бы радар в пересказ технических обсуждений.
  if (!client.length && !money) return null;

  let score = 0;
  if (client.length) score += 3;
  if (money) score += 2;
  if (findMatches(haystack, STRONG_INTENT).length) score += 2;
  if (role.length) score += 1;
  score += Math.min(task.length, 2);
  if (findMatches(haystack, URGENCY).length) score += 1;

  const level = score >= 6 ? "hot" : score >= 4 ? "warm" : "cold";

  return {
    // Поля названы так же, как у недвижимости: уведомление и разбор истории
    // печатают их одинаково, не зная, какая тема сработала.
    geo: role,
    topic: task,
    intent: client,
    buySignals: client,
    score,
    level,
    badge: level === "hot" ? "🔥" : level === "warm" ? "🟡" : "⚪️",
    chatTitle,
  };
}
