// Словари третьей темы: тёплый контакт — человек ДО покупки.
//
// Первые две темы ищут того, кто уже сказал, чего хочет. Эта ищет раньше:
// человек переезжает, оформляет ВНЖ, открывает компанию, перевозит семью.
// Жильё ему понадобится через 3–12 месяцев, и прямо сейчас за него никто
// не борется — он ещё не произнёс слово «купить».
//
// Отсюда и правило: это НЕ лид, и обращаться с ним как с лидом — вернейший
// способ его потерять. Поэтому у темы отдельный чат и своя подпись.
//
// Тема самая шумная из трёх: чаты релокантов состоят из слова «переезжаю».
// Поэтому одного признака переезда мало — нужен ещё признак того, что
// человек устраивается надолго и при деньгах: семья, бизнес, ВНЖ, счёт
// в банке. Турист и тот, кто ищет работу, отсекаются жёстко.

