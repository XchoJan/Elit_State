/**
 * Реклама услуг релокации. Тема тёплого контакта притягивает её сильнее
 * прочих: юристы и визовые агентства пишут ровно теми же словами — «ВНЖ»,
 * «резидентство», «компания в Дубае». Отличает их голос: клиент просит
 * помощи, а агентство её предлагает.
 */
const SERVICE_AD = [
  "помогаем",
  "поможем",
  "оформим",
  "делаем внж",
  "услуги по релокации",
  "релокация под ключ",
  "внж под ключ",
  "обращайтесь",
  "консультация бесплатн",
  "наши услуги",
  "пишите в личку",
  "пишите в лс",
];

export const MIN_LENGTH = 30;

function findMatches(haystack, list) {
  return list.filter((word) => haystack.includes(word));
}

/**
 * Разбирает сообщение как возможный тёплый контакт.
 *
 * Правило: страна + признак переезда ИЛИ статуса + признак того, что человек
 * оседает надолго (семья, бизнес, ВНЖ). Одного «переезжаю в Ереван» мало —
 * так пишет половина чата релокантов, и половина из них через месяц уедет.
 */
export function matchWarmLead(text, chatTitle = "") {
  if (!text || text.length < MIN_LENGTH) return null;

  const haystack = normalize(text);

  // Общий стоп-лист покупки подходит и сюда: ищущие работу, туристы
  // и реклама здесь такой же мусор.
  if (findMatches(haystack, STOP).length) return null;
  if (findMatches(haystack, TRANSIENT).length) return null;
  if (findMatches(haystack, SERVICE_AD).length) return null;
  // Свёрстанное объявление — это витрина, а не человек. Здесь так рекламируют
  // пакеты услуг по релокации: «ВНЖ — от $X», «Счёт в банке — от $Y».
  if (looksLikeListing(text)) return null;

  const geo = findMatches(haystack, GEO);
  const geoFromChat = findMatches(normalize(chatTitle), GEO);
  if (!geo.length && !geoFromChat.length) return null;

  const relocation = findMatches(haystack, RELOCATION);
  const residency = findMatches(haystack, RESIDENCY);
  const capacity = findMatches(haystack, CAPACITY);
  const family = findMatches(haystack, FAMILY);

  // Событие: человек переезжает или оформляет статус.
  if (!relocation.length && !residency.length) return null;

  // Основание считать, что это надолго и всерьёз. Без него остаётся
  // «переезжаю» — самое частое слово в чатах релокантов и самое пустое.
  const anchors = [...residency, ...capacity, ...family];
  if (!anchors.length) return null;

  let score = 0;
  if (capacity.length) score += 3; // бизнес и счета — это деньги
  if (residency.length) score += 2;
  if (family.length) score += 2;
  if (relocation.length) score += 1;
  if (geo.length) score += 1; // страна названа прямо, а не взята из чата

  const level = score >= 6 ? "hot" : score >= 4 ? "warm" : "cold";

  return {
    // Названия полей как у остальных тем: уведомление печатает их одинаково.
    geo: geo.length ? geo : geoFromChat.map((g) => `${g} (из названия чата)`),
    topic: [...relocation, ...residency],
    intent: [...capacity, ...family],
    buySignals: capacity,
    score,
    level,
    badge: level === "hot" ? "🔥" : level === "warm" ? "🟡" : "⚪️",
  };
}
