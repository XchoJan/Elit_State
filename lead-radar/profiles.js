/**
 * Включены только профили, которым задан свой чат. Отдельный чат — это не
 * настройка, а условие работы: без него находки некуда девать, а сваливать
 * их в чужой канал нельзя.
 */
export const PROFILES = ALL.filter((p) => p.chatIds.length);

/** Профили, у которых чат не настроен, — чтобы сказать об этом при старте. */
export const DISABLED_PROFILES = ALL.filter((p) => !p.chatIds.length);

/**
 * Чаты, куда радар пишет сам, во всех возможных написаниях id.
 *
 * Считается один раз и на все профили. Раньше этот список собирали в трёх
 * местах по отдельности — и трижды ловили одну и ту же ошибку: радар находил
 * собственные уведомления (в них есть и город, и «квартира», и вопрос),
 * пересылал их себе же и заводился по кругу.
 */
export const OWN_CHAT_IDS = new Set(
  ALL.flatMap((p) => p.chatIds).flatMap((id) => [
    id,
    id.replace("-100", ""),
    id.replace(/^-/, ""),
    id.replace("-100", "").replace(/^-/, ""),
  ])
);

/** Наш ли это чат — по объекту чата из библиотеки или по голому id. */
export function isOwnChat(chatOrId) {
  const raw = typeof chatOrId === "object" ? chatOrId?.id : chatOrId;
  if (!raw) return false;
  const id = String(raw);
  return (
    OWN_CHAT_IDS.has(id) ||
    OWN_CHAT_IDS.has(`-${id}`) ||
    OWN_CHAT_IDS.has(`-100${id}`) ||
    OWN_CHAT_IDS.has(id.replace("-100", "").replace(/^-/, ""))
  );
}
