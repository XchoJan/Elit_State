// Профили поиска: что радар ищет и куда это отправляет.
//
// Профиль — это связка «словари + поисковые фразы + свой чат для находок».
// Движок (index.js, globalSearch.js) о темах ничего не знает: он прогоняет
// сообщение через каждый включённый профиль и шлёт результат в его канал.
// Чтобы добавить третью тему, достаточно дописать сюда ещё один объект.
//
// Разделение по каналам здесь не косметическое: у каждой темы свой чат, и
// чужие находки не должны попадать в чат отдела продаж — иначе настоящие
// лиды потеряются в потоке посторонней темы.

import { matchLead } from "./keywords.js";
import { matchWarmLead } from "./keywordsWarm.js";

/** Список id чатов через запятую → массив без пустых. */
function chatIds(value) {
  return String(value ?? "")
    .split(",")
    .map((id) => id.trim())
    .filter(Boolean);
}

