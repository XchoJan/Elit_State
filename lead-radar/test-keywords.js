function run(title, cases, matcher) {
  console.log(`\n=== ${title} ===`);
  let ok = 0;
  for (const [text, chat, expected, why] of cases) {
    const m = matcher(text, chat);
    const got = Boolean(m);
    const correct = got === expected;
    if (correct) ok++;
    console.log(
      `${correct ? "✅" : "❌"} ${got ? `совпало (${m.score} ${m.badge})` : "мимо        "} ` +
        `| ${why}\n     ${text.slice(0, 70)}`
    );
    if (!correct && m) {
      console.log(`     сработало: ${[...m.geo, ...m.topic, ...m.intent].join(", ")}`);
    }
  }
  console.log(`Верно: ${ok} из ${cases.length}`);
  return ok === cases.length;
}

